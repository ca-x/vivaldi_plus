import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {gzipSync, constants} from 'node:zlib';

const fixtures = [
  {name:'Stored', input:Buffer.from('stored: hello\0世界\n'), options:{level:0}, block:0},
  {name:'Fixed', input:Buffer.from('Vivaldi++ portable browser settings.\n'.repeat(100)), options:{strategy:constants.Z_FIXED}, block:1},
  {name:'Dynamic', input:Buffer.from(Array.from({length:16000},(_,i)=>String.fromCharCode(32+(i*i+17*i)%41)).join('')), options:{level:9}, block:2},
  {name:'Utf8', input:Buffer.from('界面设置 · Vivaldi++\n'.repeat(1500)), options:{level:9}},
];
let seed=0x12345678;
const prefix=Buffer.alloc(1024);
for(let i=0;i<prefix.length;i++){seed=(Math.imul(seed,1664525)+1013904223)>>>0;prefix[i]=seed>>>24;}
fixtures.push({name:'LongDistance',input:Buffer.concat([prefix,prefix]),options:{level:9}});
const lines=['// Generated by node tests/generate-gzip-fixtures.mjs using Node zlib.','#pragma once','#include <cstdint>'];
for(const fixture of fixtures){
  const gzip=gzipSync(fixture.input,fixture.options);
  const block=(gzip[10]>>>1)&3;
  if(fixture.block!==undefined&&fixture.block!==block)throw new Error(`${fixture.name}: unexpected block type ${block}`);
  lines.push(`inline constexpr uint8_t kGzip${fixture.name}[] = {`);
  for(let i=0;i<gzip.length;i+=24)lines.push('  '+Array.from(gzip.subarray(i,i+24),b=>'0x'+b.toString(16).padStart(2,'0')).join(',')+',');
  lines.push('};');
  console.log(`${fixture.name}: expected=${fixture.input.length} gzip=${gzip.length} block=${block}`);
}
fs.writeFileSync(fileURLToPath(new URL('./fixtures/gzip_cases.h',import.meta.url)),lines.join('\n')+'\n');
